# --- Core Prediction Logic ---
def compute_inventory_predictions(
    items: List[Dict[str, Any]],
    method: str = "weighted_mean",
    weighting_type: str = "linear",
    service_level: float = 0.95,
    horizon: int = 1,
    alpha: float = 0.3,
    beta: float = 0.2
) -> Dict[str, Any]:
    """
    Runs selected forecasting method and inventory optimization on each item.
    Supported methods: weighted_mean, holt_winters, ensemble, machine_learning
    """
    processed_items = []
    total_stock_value = 0.0
    total_reorder_investment = 0.0
    critical_risk_count = 0
    reorder_needed_count = 0
    overstock_count = 0

    for it in items:
        sku = it.get("sku", "UNKNOWN")
        name = it.get("name", sku)
        category = it.get("category", "General")
        current_stock = float(it.get("current_stock", 0.0))
        lead_time = float(it.get("lead_time_days", 14.0))
        unit_cost = float(it.get("unit_cost", 10.0))
        unit_price = float(it.get("unit_price", unit_cost * 1.5))
        demand_history = it.get("demand_history", [])

        # ---------- 1. Demand Forecast ----------
        if method == "machine_learning":
            ml_predictor = InventoryMLPredictor()
            forecast_res = ml_predictor.predict(
                history=demand_history,
                horizon=horizon
            )
            # Ensure ML predictor returns the required keys; provide fallbacks if missing
            if "forecast" not in forecast_res:
                forecast_res["forecast"] = [0.0] * horizon
            if "next_period" not in forecast_res:
                forecast_res["next_period"] = forecast_res["forecast"][0] if forecast_res["forecast"] else 0.0
            if "std_dev" not in forecast_res:
                forecast_res["std_dev"] = 5.0
            if "method" not in forecast_res:
                forecast_res["method"] = "Machine Learning"
            if "formula" not in forecast_res:
                forecast_res["formula"] = "ML model (implementation specific)"
            if "explanation" not in forecast_res:
                forecast_res["explanation"] = "Forecast generated by a machine learning model."
            if "weight_breakdown" not in forecast_res:
                forecast_res["weight_breakdown"] = []
        elif method == "holt_winters":
            forecast_res = HoltWintersPredictor.predict(
                history=demand_history,
                horizon=horizon,
                alpha=alpha,
                beta=beta
            )
        elif method == "ensemble":
            res_wm = WeightedMeanPredictor.predict(history=demand_history, horizon=horizon, weighting_type=weighting_type)
            res_hw = HoltWintersPredictor.predict(history=demand_history, horizon=horizon, alpha=alpha, beta=beta)
            combined_forecast = [round((w + h) / 2.0, 2) for w, h in zip(res_wm["forecast"], res_hw["forecast"])]
            next_period = combined_forecast[0] if combined_forecast else 0.0
            std_dev = (res_wm["std_dev"] + res_hw["std_dev"]) / 2.0
            forecast_res = {
                "forecast": combined_forecast,
                "next_period": next_period,
                "total_horizon_demand": round(sum(combined_forecast), 2),
                "std_dev": round(std_dev, 2),
                "method": "Ensemble (WMA + Holt's)",
                "formula": "0.5 * (WMA) + 0.5 * (Holt_Linear)",
                "explanation": "Blended forecast combining weighted historical velocity with trend smoothing.",
                "weight_breakdown": []
            }
        else:  # default: weighted_mean
            forecast_res = WeightedMeanPredictor.predict(
                history=demand_history,
                horizon=horizon,
                weighting_type=weighting_type
            )

        predicted_monthly_demand = float(forecast_res.get("next_period", 0.0))
        historical_std = float(forecast_res.get("std_dev", 5.0))

        # ---------- 2. Inventory Optimization ----------
        opt_res = InventoryOptimizationEngine.calculate_metrics(
            current_stock=current_stock,
            predicted_demand_per_month=predicted_monthly_demand,
            historical_std_dev=historical_std,
            lead_time_days=lead_time,
            service_level=service_level,
            unit_cost=unit_cost,
            unit_price=unit_price
        )

        # Accumulate totals
        total_stock_value += opt_res["stock_value"]
        total_reorder_investment += opt_res["reorder_investment"]
        if opt_res["risk_level"] == "CRITICAL":
            critical_risk_count += 1
        if opt_res["needs_reorder"]:
            reorder_needed_count += 1
        if opt_res["risk_level"] == "OVERSTOCK":
            overstock_count += 1

        processed_item = {
            "sku": sku,
            "name": name,
            "category": category,
            "current_stock": current_stock,
            "lead_time_days": lead_time,
            "unit_cost": unit_cost,
            "unit_price": unit_price,
            "demand_history": demand_history,
            "next_period_forecast": predicted_monthly_demand,
            "horizon_forecast": forecast_res.get("forecast", []),
            "forecast_method": forecast_res.get("method", method),
            "forecast_formula": forecast_res.get("formula", ""),
            "forecast_explanation": forecast_res.get("explanation", ""),
            "weights_breakdown": forecast_res.get("weight_breakdown", []),
            # Inventory optimization fields
            "daily_demand": opt_res["daily_demand"],
            "lead_time_demand": opt_res["lead_time_demand"],
            "safety_stock": opt_res["safety_stock"],
            "reorder_point": opt_res["reorder_point"],
            "days_of_inventory": opt_res["days_of_inventory"],
            "needs_reorder": opt_res["needs_reorder"],
            "recommended_order_qty": opt_res["recommended_order_qty"],
            "status": opt_res["status"],
            "risk_level": opt_res["risk_level"],
            "status_badge": opt_res["status_badge"],
            "stock_value": opt_res["stock_value"],
            "reorder_investment": opt_res["reorder_investment"],
            "annual_holding_cost": opt_res["annual_holding_cost"]
        }
        processed_items.append(processed_item)

    # Sort: critical risks & reorders first
    risk_rank = {"CRITICAL": 0, "HIGH": 1, "MEDIUM": 2, "OVERSTOCK": 3, "HEALTHY": 4}
    processed_items.sort(key=lambda x: (risk_rank.get(x["risk_level"], 5), -x["reorder_investment"]))

    summary_stats = {
        "total_items": len(processed_items),
        "reorder_needed_count": reorder_needed_count,
        "critical_risk_count": critical_risk_count,
        "overstock_count": overstock_count,
        "healthy_count": len(processed_items) - reorder_needed_count - overstock_count,
        "total_stock_value": round(total_stock_value, 2),
        "total_reorder_investment": round(total_reorder_investment, 2),
        "method_used": method.replace("_", " ").title(),
        "service_level_pct": int(service_level * 100),
        "horizon_periods": horizon
    }

    return {"items": processed_items, "summary": summary_stats}

