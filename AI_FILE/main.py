@app.post("/api/predict")
def predict_json(req: PredictRequest):
    """Accepts inventory items as JSON and runs predictions."""
    return compute_inventory_predictions(
        items=req.items,
        method=req.method or "weighted_mean",
        weighting_type=req.weighting_type or "linear",
        service_level=req.service_level or 0.95,
        horizon=req.horizon or 1,
        alpha=req.alpha or 0.3,
        beta=req.beta or 0.2
    )

@app.post("/api/upload")
async def upload_file(
    file: UploadFile = File(...),
    method: str = Form("weighted_mean"),
    weighting_type: str = Form("linear"),
    service_level: float = Form(0.95),
    horizon: int = Form(1),
    alpha: float = Form(0.3),
    beta: float = Form(0.2)
):
    """Uploads Excel or CSV file, parses data and runs predictions."""
    try:
        content = await file.read()
        items = InventoryDataLoader.load_from_bytes(content, file.filename)
        if not items:
            raise HTTPException(status_code=400, detail="Could not extract valid inventory records from file.")
        return compute_inventory_predictions(
            items=items,
            method=method,
            weighting_type=weighting_type,
            service_level=service_level,
            horizon=horizon,
            alpha=alpha,
            beta=beta
        )
    except Exception as e:
        raise HTTPException(status_code=400, detail=f"File processing error: {str(e)}")

@app.post("/api/predict/google-sheet")
def predict_google_sheet(req: GoogleSheetRequest):
    """Loads inventory from a public Google Sheet URL and computes forecasts."""
    try:
        items = InventoryDataLoader.load_from_google_sheet(req.sheet_url)
        if not items:
            raise HTTPException(status_code=400, detail="No inventory items found in Google Sheet.")
        return compute_inventory_predictions(
            items=items,
            method=req.method or "weighted_mean",
            weighting_type=req.weighting_type or "linear",
            service_level=req.service_level or 0.95,
            horizon=req.horizon or 1,
            alpha=req.alpha or 0.3,
            beta=req.beta or 0.2
        )
    except Exception as e:
        raise HTTPException(status_code=400, detail=f"Google Sheets error: {str(e)}")

